#!/usr/bin/env node
/**
 * Grove host daemon — runs on the grove machine (the Mac that hosts the site).
 *
 * This machine is the new host for kod88vn/grove. The repo is public and the
 * account is on the free plan, so GitHub Actions cannot use a self-hosted
 * runner. Instead:
 *
 *   - CI (free GitHub-hosted runners) validates every commit/PR.
 *   - This daemon DEPLOYS on the machine:
 *       1. A signed webhook (POST /deploy/<token>) lets CI trigger instantly;
 *          it is exposed through Tailscale Funnel.
 *       2. A polling fallback (every POLL_INTERVAL_SECONDS) checks GitHub for a
 *          new master commit whose checks are green — so a missed webhook still
 *          gets deployed.
 *   - It runs `ops/deploy/deploy.sh <sha>` from a dedicated checkout
 *     (GROVE_CHECKOUT_DIR) and reports the result to GitHub as a commit status.
 *
 * Zero npm dependencies. Needs Node 18+ (global fetch) and the `gh` CLI.
 * Configuration: ~/.grove/host.env (see ops/deploy/host.env.example).
 * Supervision: launchd plist generated by ops/deploy/install-host.sh.
 */
import http from 'node:http'
import { spawn } from 'node:child_process'
import { readFileSync, existsSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { timingSafeEqual } from 'node:crypto'

// ── config ────────────────────────────────────────────────────────────────────
const home = os.homedir()
const groveHome = process.env.GROVE_HOME || path.join(home, '.grove')
const envFile = path.join(groveHome, 'host.env')
const checkoutDir = process.env.CHECKOUT_DIR || path.join(groveHome, 'checkout')
const logsDir = path.join(groveHome, 'logs')
const stateFile = path.join(groveHome, 'state.json')

function loadEnvFile(file) {
  if (!existsSync(file)) return
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)=(.*)$/)
    if (!m) continue
    let v = m[2].trim()
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1)
    if (!(v in process.env)) process.env[m[1]] = v
  }
}
loadEnvFile(envFile)

const REPO = process.env.GROVE_REPO || 'kod88vn/grove'
const API = `https://api.github.com/repos/${REPO}`
const TOKEN = process.env.GITHUB_TOKEN || ''
const DAEMON_PORT = Number(process.env.DAEMON_PORT || 8080)
const DEPLOY_TOKEN = process.env.GROVE_DEPLOY_TOKEN || ''
const POLL_INTERVAL_S = Number(process.env.POLL_INTERVAL_SECONDS || 60)
const CHECKS_TIMEOUT_S = Number(process.env.CHECKS_TIMEOUT_SECONDS || 30 * 60)
const DEPLOY_COOLDOWN_MS = Number(process.env.DEPLOY_COOLDOWN_MS || 5 * 60 * 1000)
// When the webhook is exposed as a path prefix on a shared Tailscale Funnel
// host (e.g. https://studio.tail03716c.ts.net/grove), the proxy forwards the
// full path, so the daemon must accept the same prefix. Empty by default.
const WEBHOOK_PREFIX = (process.env.WEBHOOK_PATH_PREFIX || '').replace(/\/+$/, '')
// Public base URL of this daemon's webhook (same value as the repo variable
// GROVE_DEPLOY_URL). Used to verify reachability instead of re-running the CLI.
const DEPLOY_URL = process.env.GROVE_DEPLOY_URL || ''

mkdirSync(logsDir, { recursive: true })

// ── logging ───────────────────────────────────────────────────────────────────
function log(...args) {
  const line = `[${new Date().toISOString()}] ${args.join(' ')}`
  console.log(line)
}

// ── state ─────────────────────────────────────────────────────────────────────
let state = { lastDeploySha: '', lastDeployStarted: 0, lastStatus: '', deploying: false }
function loadState() {
  try {
    state = { ...state, ...JSON.parse(readFileSync(stateFile, 'utf8')) }
  } catch {}
}
function saveState() {
  try { writeFileSync(stateFile, JSON.stringify(state, null, 2)) } catch (e) { log('state write failed:', e.message) }
}
loadState()

// ── github helpers ────────────────────────────────────────────────────────────
async function ghFetch(url, opts = {}) {
  const res = await fetch(url, {
    ...opts,
    headers: {
      'user-agent': 'grove-host-daemon',
      'accept': 'application/vnd.github+json',
      ...(TOKEN ? { authorization: `Bearer ${TOKEN}` } : {}),
      ...(opts.headers || {}),
    },
  })
  if (!res.ok) throw new Error(`GitHub ${res.status} for ${url}`)
  return res.json()
}

/** Latest commit on master. */
async function latestMasterSha() {
  const ref = await ghFetch(`${API}/commits/heads/master`)
  return ref.sha
}

/**
 * Wait until all check runs for a SHA are complete with no failures.
 * Returns 'green', 'red', or 'timeout'.
 */
async function waitForChecks(sha) {
  const started = Date.now()
  while (Date.now() - started < CHECKS_TIMEOUT_S * 1000) {
    let page = 1
    let runs = []
    for (;;) {
      const batch = await ghFetch(`${API}/commits/${sha}/check-runs?per_page=100&page=${page}`)
      runs = runs.concat(batch.check_runs || [])
      if ((batch.total_count || 0) <= runs.length) break
      page += 1
      if (page > 20) break
    }
    const failed = runs.filter((r) => r.conclusion && r.conclusion !== 'success' && r.conclusion !== 'skipped' && r.conclusion !== 'neutral')
    const pending = runs.filter((r) => r.status !== 'completed')
    if (runs.length === 0) {
      // No CI produced any check run for this commit. Rather than block the
      // site forever on a disabled/renamed workflow, deploy after a grace
      // period with a warning.
      if (Date.now() - started > 10 * 60 * 1000) {
        log(`no check runs for ${sha.slice(0, 7)} after 10 min — deploying anyway (CI may be disabled)`)
        return 'green'
      }
    } else if (failed.length > 0) {
      return 'red'
    } else if (pending.length === 0) {
      return 'green'
    }
    await sleep(POLL_INTERVAL_S * 1000)
  }
  return 'timeout'
}

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms))
}

// ── deploy ────────────────────────────────────────────────────────────────────
async function runDeploy(sha, trigger) {
  if (state.deploying) {
    log(`deploy for ${sha.slice(0, 7)} requested (${trigger}) but a deploy is already running — skipping`)
    return
  }
  if (state.lastDeploySha === sha && state.lastStatus === 'success' && Date.now() - state.lastDeployStarted < DEPLOY_COOLDOWN_MS) {
    log(`deploy for ${sha.slice(0, 7)} requested (${trigger}) — already deployed recently, skipping`)
    return
  }
  state.deploying = true
  saveState()
  log(`=== deploy ${sha.slice(0, 7)} (trigger: ${trigger}) ===`)
  state.lastDeployStarted = Date.now()

  const script = path.join(checkoutDir, 'ops', 'deploy', 'deploy.sh')
  const child = spawn('bash', [script, sha], {
    cwd: checkoutDir,
    env: process.env,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  let out = ''
  child.stdout.on('data', (d) => { out += d; process.stdout.write(d) })
  child.stderr.on('data', (d) => { out += d; process.stderr.write(d) })
  child.on('error', (e) => {
    log(`deploy spawn error: ${e.message}`)
    state.deploying = false
    state.lastStatus = 'failure'
    saveState()
  })
  const code = await new Promise((r) => child.on('close', r))
  state.deploying = false
  state.lastStatus = code === 0 ? 'success' : 'failure'
  state.lastDeploySha = code === 0 ? sha : state.lastDeploySha
  saveState()
  // Keep the log tail for debugging (rotating single file).
  try {
    writeFileSync(path.join(logsDir, 'deploy-last.log'), `trigger=${trigger}\nsha=${sha}\nexit=${code}\n${out.slice(-40000)}\n`)
  } catch {}
  log(`=== deploy ${sha.slice(0, 7)} finished: ${code === 0 ? 'SUCCESS' : `FAILED (exit ${code})`} ===`)
  if (code !== 0) {
    // One automatic retry after 2 minutes for transient failures (docker daemon hiccup etc.).
    log('retrying once after 2 minutes…')
    await sleep(2 * 60 * 1000)
    state.deploying = true
    saveState()
    const retry = spawn('bash', [script, sha], { cwd: checkoutDir, env: process.env, stdio: ['ignore', 'pipe', 'pipe'] })
    retry.stdout.pipe(process.stdout)
    retry.stderr.pipe(process.stderr)
    const rc2 = await new Promise((r) => retry.on('close', r))
    state.deploying = false
    if (rc2 === 0) {
      state.lastStatus = 'success'
      state.lastDeploySha = sha
      log(`retry of ${sha.slice(0, 7)} SUCCEEDED`)
    } else {
      state.lastStatus = 'failure'
      log(`retry of ${sha.slice(0, 7)} failed (exit ${rc2})`)
    }
    saveState()
  }
}

// ── polling loop (fallback + catch-up) ───────────────────────────────────────
async function pollLoop() {
  for (;;) {
    try {
      if (!state.deploying) {
        const sha = await latestMasterSha()
        if (sha !== state.lastDeploySha) {
          if (!state.lastDeploySha) {
            log(`first run — current master is ${sha.slice(0, 7)}; deploying if not already live`)
          } else {
            log(`new master commit ${sha.slice(0, 7)} (was ${state.lastDeploySha.slice(0, 7)})`)
          }
          const verdict = await waitForChecks(sha)
          if (verdict === 'green') {
            await runDeploy(sha, 'poll')
          } else if (verdict === 'red') {
            log(`checks red for ${sha.slice(0, 7)} — will retry next poll`)
          } else {
            log(`checks timed out for ${sha.slice(0, 7)} — will retry next poll`)
          }
        }
      }
    } catch (e) {
      log(`poll error: ${e.message}`)
    }
    await sleep(POLL_INTERVAL_S * 1000)
  }
}

// ── webhook (Tailscale Funnel) ───────────────────────────────────────────────
function tokenValid(urlToken) {
  if (!DEPLOY_TOKEN) return false
  const a = Buffer.from(String(urlToken))
  const b = Buffer.from(DEPLOY_TOKEN)
  if (a.length !== b.length) return false
  return timingSafeEqual(a, b)
}

const server = http.createServer((req, res) => {
  const send = (code, obj) => {
    res.writeHead(code, { 'content-type': 'application/json' })
    res.end(JSON.stringify(obj))
  }
  const u = req.url || ''
  if (req.method === 'GET' && u === `${WEBHOOK_PREFIX}/healthz`) {
    return send(200, { ok: true, deploying: state.deploying, lastDeploySha: state.lastDeploySha, lastStatus: state.lastStatus, repo: REPO })
  }
  if (req.method === 'POST' && u.startsWith(`${WEBHOOK_PREFIX}/deploy/`)) {
    if (!tokenValid(u.slice(`${WEBHOOK_PREFIX}/deploy/`.length))) {
      return send(401, { error: 'bad token' })
    }
    let body = ''
    req.on('data', (d) => { body += d; if (body.length > 65536) req.destroy() })
    req.on('close', () => {})
    req.on('error', () => {})
    req.on('end', () => {
      let sha = null
      try { sha = JSON.parse(body || '{}').sha } catch {}
      if (!sha || !/^[a-f0-9]{7,40}$/.test(sha)) {
        return send(400, { error: 'missing or invalid sha' })
      }
      send(202, { accepted: true, sha, deploying: state.deploying })
      // Fire and forget; the poll loop is the backstop.
      runDeploy(sha, 'webhook').catch((e) => log(`webhook deploy error: ${e.message}`))
    })
    return
  }
  send(404, { error: 'not found' })
})

server.listen(DAEMON_PORT, '127.0.0.1', () => {
  log(`grove host daemon up: repo=${REPO} webhook=127.0.0.1:${DAEMON_PORT} checkout=${checkoutDir} poll=${POLL_INTERVAL_S}s`)
  if (!DEPLOY_TOKEN) log('WARNING: GROVE_DEPLOY_TOKEN not set — webhook disabled (polling still works)')
  if (!TOKEN) log('WARNING: GITHUB_TOKEN not set — cannot poll GitHub or report status')
})

// ── tailscale funnel (webhook reachability) ───────────────────────────────────
// `tailscale funnel <port>` is idempotent: it succeeds immediately when the port
// is already funneled. Called without a TTY it does not prompt. On a shared
// Funnel host (one 443 listener serving several path-routed apps) the route is
// a path — `tailscale funnel http://127.0.0.1:<port><prefix>` adds it. If the
// CLI and the running tailscaled build disagree on the serve-config protocol
// this fails harmlessly: the polling fallback deploys regardless.
let funnelBusy = false
async function ensureFunnel() {
  if (funnelBusy) return
  // If the configured public URL already reaches us, the route exists (possibly
  // as a path on a shared Funnel host) — do not touch the serve config.
  if (DEPLOY_URL) {
    try {
      const res = await fetch(`${DEPLOY_URL.replace(/\/+$/, '')}${WEBHOOK_PREFIX}/healthz`, { signal: AbortSignal.timeout(10_000) })
      if (res.ok) return
    } catch {}
  }
  funnelBusy = true
  try {
    const target = WEBHOOK_PREFIX ? `http://127.0.0.1:${DAEMON_PORT}${WEBHOOK_PREFIX}` : String(DAEMON_PORT)
    const r = spawn('tailscale', ['funnel', target], { stdio: ['ignore', 'pipe', 'pipe'] })
    r.stdout.on('data', (d) => process.stdout.write(d))
    r.stderr.on('data', (d) => process.stderr.write(d))
    r.on('close', (code) => {
      funnelBusy = false
      if (code !== 0) log(`tailscale funnel ${target} exited ${code} (non-fatal — polling fallback still deploys; will retry hourly)`)
    })
    r.on('error', (e) => { funnelBusy = false; log(`tailscale funnel failed: ${e.message} (polling fallback still works)`) })
  } catch (e) {
    funnelBusy = false
    log(`funnel check failed (non-fatal): ${e.message}`)
  }
}

process.on('SIGTERM', () => { log('SIGTERM — shutting down'); process.exit(0) })
process.on('SIGINT', () => { log('SIGINT — shutting down'); process.exit(0) })

ensureFunnel()
setInterval(ensureFunnel, 3600 * 1000)
pollLoop()
